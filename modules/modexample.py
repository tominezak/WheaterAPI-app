pi = 3.14149

def square(x):
    """Returns the square of x."""
    return x ** 2
def cube(x):
    """Returns the cube of x."""
    return x ** 3
def circumference(radius):
    """Returns the circumference of a circle with the given radius."""
    return 2 * pi * radius
def area(radius):
    """Returns the area of a circle with the given radius."""
    return pi * (radius ** 2)